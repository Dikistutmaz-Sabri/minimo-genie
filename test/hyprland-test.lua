-- Nested test Hyprland for minimo-genie (runs as a window inside Plasma).
-- Nothing of ~/.config/hypr is read.
hl.config({ autogenerated = false })
hl.monitor({ output = "", mode = "1280x800", position = "0x0", scale = 1 })
hl.config({
	general = { gaps_in = 4, gaps_out = 4, border_size = 0 },
	decoration = { rounding = 12 },
	misc = { disable_hyprland_logo = true, disable_splash_rendering = true, disable_xdg_env_checks = true },
})
for leaf, speed in pairs({ windowsIn = 3, windowsOut = 3, windowsMove = 4, workspaces = 5, fade = 3 }) do
	hl.animation({ leaf = leaf, enabled = true, speed = speed, bezier = "default" })
end
-- as in Minimo: free windows
hl.on("window.open", function(w)
	if w and not w.floating then hl.dispatch(hl.dsp.window.float({ action = "set", window = "address:" .. w.address })) end
end)
